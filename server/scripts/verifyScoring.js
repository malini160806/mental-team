// Checks the stress model against the survey spec and prints the
// feature-direction table as Markdown.
//
//   npm run verify:scoring                                   # checks + table
//   npm run verify:scoring > docs/feature-directions.md      # refresh the doc

import assert from 'node:assert/strict';
import { QUESTION_SPEC, LETTERS } from '../../shared/surveySpec.js';
import { FEATURES, NON_SCORED_COLUMNS, LEVELS, MODEL_VERSION, assess } from '../../shared/stressModel.js';

// 1. Every column of every question is either scored or explicitly excluded,
//    and each scored feature appears exactly once.
const columns = QUESTION_SPEC.flatMap((q) => q.columns.map((col) => ({ col, qid: q.id })));
const scoredColumns = columns.filter(({ col }) => !NON_SCORED_COLUMNS.includes(col));
const names = FEATURES.map((f) => f.name);
assert.equal(new Set(names).size, names.length, 'a feature appears more than once');
assert.deepEqual(new Set(scoredColumns.map((c) => c.col)), new Set(names), 'scored columns ≠ features');
assert.equal(
  FEATURES.reduce((n, f) => n + f.sources.length, 0),
  scoredColumns.length,
  'every (question, column) pair maps to exactly one feature source',
);
QUESTION_SPEC.forEach((q) => {
  assert.ok(FEATURES.some((f) => f.sources.includes(q.id)), `Q${q.id} contributes no feature`);
});

// 2. End-to-end sanity checks.
const all = (letter) => Object.fromEntries(QUESTION_SPEC.map((q) => [q.id, letter]));
const maxTotal = FEATURES.reduce((n, f) => n + f.max, 0);

const best = assess(all('A'));
const worst = assess(all('E'));
assert.equal(best.completeness, 'complete');
assert.equal(best.maximumScore, maxTotal);
assert.equal(Object.keys(best.adjustedFeatures).length, FEATURES.length);
assert.ok(best.stressScore < worst.stressScore, 'all-A should score lower than all-E');
assert.equal(best.stressLevel, 'Low');
assert.equal(worst.stressLevel, 'High');

// Protective features are reversed, risk features are not.
assert.equal(best.adjustedFeatures.Sleep_Adequacy, 0); // 4 → 0
assert.equal(worst.adjustedFeatures.Sleep_Adequacy, 4); // 0 → 4
assert.equal(worst.adjustedFeatures.Overthinking, 4);

// Partial answers: missing questions are excluded, not counted as 0.
const partial = assess({ 13: 'E', 20: 'E' });
assert.equal(partial.completeness, 'partial');
assert.equal(partial.missingQuestions.length, QUESTION_SPEC.length - 2);
assert.equal(partial.maximumScore, 7 * 4);
assert.equal(partial.stressScore, round(((4 + 4 + 4) + (4 + 4 + 4 + 4)) / 28 * 100));
assert.equal(assess({}).stressScore, null);

// 3. Markdown table.
const sourceLabel = (f) => f.sources.map((q) => `Q${q}`).join(' + ');
const lines = [
  `# Stress score — feature directions (${MODEL_VERSION})`,
  '',
  'Generated by `npm run verify:scoring`. Answer → score mappings come from',
  '`shared/surveySpec.js` (the survey document); directions from `shared/stressModel.js`.',
  '',
  `- Scored features: **${FEATURES.length}** (from ${scoredColumns.length} question columns across ${QUESTION_SPEC.length} questions)`,
  `- Not scored: ${NON_SCORED_COLUMNS.map((c) => `\`${c}\``).join(', ')} (text label)`,
  `- Shared features (mean of their sources, counted once): ${FEATURES.filter((f) => f.sources.length > 1).map((f) => `${f.name} (${sourceLabel(f)})`).join(', ')}`,
  `- Maximum raw score with all questions answered: **${maxTotal}**`,
  `- Levels: ${LEVELS.map((l, i) => `${i ? LEVELS[i - 1].max + 1 : 0}–${l.max} ${l.level}`).join(' · ')}`,
  `- Range check: all-A → ${best.stressScore} (${best.stressLevel}), all-E → ${worst.stressScore} (${worst.stressLevel})`,
  '',
  '| # | Feature | Source question | Original range | Type | Adjustment | Reason |',
  '|---|---|---|---|---|---|---|',
  ...FEATURES.map((f, i) => {
    const keys = f.sources.map((id) => QUESTION_SPEC.find((s) => s.id === id).key).join(', ');
    const type = f.direction === 'risk' ? 'Risk' : 'Protective';
    const formula = f.direction === 'risk' ? 'score' : `${f.max} − score`;
    return `| ${i + 1} | ${f.name} | ${sourceLabel(f)} (${keys}) | 0–${f.max} | ${type} | ${formula} | ${f.reason} |`;
  }),
  '',
  `Risk: ${FEATURES.filter((f) => f.direction === 'risk').length} · Protective: ${FEATURES.filter((f) => f.direction === 'protective').length} · Options per question: ${LETTERS.join('/')}`,
];
console.log(lines.join('\n'));

function round(n) {
  return Math.round(n * 100) / 100;
}
